// 从 prototype.html 抽取 Tabler 风格图标 sprite，生成 @duo/ui 的 IconSprite.tsx
// 用法：node scripts/gen-icon-sprite.mjs
import { readFileSync, writeFileSync } from "node:fs";

const html = readFileSync(new URL("../prototype.html", import.meta.url), "utf8");
const body = html.slice(html.indexOf("<svg width=\"0\""), html.indexOf("</defs></svg>") + "</defs></svg>".length);

const jsx = body
  .replace(/^<svg width="0" height="0" style="position:absolute" aria-hidden="true">/, "")
  .replace(/stroke-width=/g, "strokeWidth=")
  .replace(/stroke-linecap=/g, "strokeLinecap=")
  .replace(/fill-rule=/g, "fillRule=")
  .replace(/clip-rule=/g, "clipRule=")
  .replace(/stroke-linejoin=/g, "strokeLinejoin=");

const ids = [...jsx.matchAll(/<symbol id="i-([a-z0-9-]+)"/g)].map(m => m[1]);

const out = `// AUTO-GENERATED by scripts/gen-icon-sprite.mjs — 源：prototype.html（勿手改，改动请重跑脚本）
import type { JSX } from "react";

/** 原型内联 sprite 的图标名清单 */
export const ICON_NAMES = ${JSON.stringify(ids, null, 0)} as const;
export type IconName = (typeof ICON_NAMES)[number];

export function IconSprite(): JSX.Element {
  return (
    <svg width="0" height="0" style={{ position: "absolute" }} aria-hidden="true" focusable="false">
      ${jsx.replace(/<\/svg>\s*$/, "")}
    </svg>
  );
}
`;

writeFileSync(new URL("../packages/ui/src/IconSprite.tsx", import.meta.url), out);
console.log(`IconSprite.tsx written · ${ids.length} icons`);
